-- 引接模块建表SQL

-- 文件引接配置表
CREATE TABLE "ETL"."T_YJ_FILE_CONFIG"
(
 "ID" BIGINT IDENTITY(1,1) NOT NULL,
 "NAME" VARCHAR(200) NOT NULL,
 "FILE_MULTI" VARCHAR(10) DEFAULT '1' NULL,
 "FILE_PATH" VARCHAR(1000) NULL,
 "FOLDER_PATH" VARCHAR(1000) NULL,
 "ANALYSIS_PROTOCOL_ID" BIGINT NULL,
 "ANALYSIS_PROTOCOL_NAME" VARCHAR(200) NULL,
 "TARGET_DATA_SOURCE_ID" BIGINT NULL,
 "TARGET_DATA_SOURCE_NAME" VARCHAR(200) NULL,
 "TARGET_SCHEMA" VARCHAR(200) NULL,
 "TASK_DATA_FLAG" INT DEFAULT 0 NULL,
 "JUMP_ROW" VARCHAR(500) NULL,
 "REMARK" VARCHAR(500) NULL,
 "PATH_TYPE" VARCHAR(20) NULL,
 "CREATE_BY" VARCHAR(100) NULL,
 "CREATE_TIME" TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NULL,
 "UPDATE_BY" VARCHAR(100) NULL,
 "UPDATE_TIME" TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NULL
);
ALTER TABLE "ETL"."T_YJ_FILE_CONFIG" ADD CONSTRAINT PRIMARY KEY("ID");

